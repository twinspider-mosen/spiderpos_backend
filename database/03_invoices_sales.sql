CREATE TABLE IF NOT EXISTS invoices (
    id VARCHAR(64) PRIMARY KEY,
    store_id VARCHAR(64) NOT NULL REFERENCES stores(id) ON DELETE CASCADE,
    order_number VARCHAR(100) NOT NULL,
    order_type VARCHAR(50) NOT NULL DEFAULT 'Sale',
    status VARCHAR(50) NOT NULL DEFAULT 'completed',
    payment_type VARCHAR(50) NOT NULL DEFAULT 'Cash',
    customer_id VARCHAR(64),
    customer_name VARCHAR(255),
    customer_previous_balance NUMERIC(14, 2) DEFAULT 0.00,
    till_no VARCHAR(50),
    invoice_date VARCHAR(50),
    invoice_time VARCHAR(50),
    invoice_subtotal NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    invoice_discount NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    invoice_tax NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    invoice_service_charges NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    invoice_delivery_charges NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    invoice_adjustment NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    invoice_total NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    cash_received NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    employee_commission NUMERIC(14, 2) DEFAULT 0.00,
    commission_paid BOOLEAN DEFAULT FALSE,
    pra_invoice_id VARCHAR(100),
    pra_sync_status VARCHAR(50) DEFAULT 'unsynced',
    reference_number VARCHAR(100),
    reason_of_cancellation TEXT,
    created_by VARCHAR(64),
    custom_fields JSONB DEFAULT '{}',
    dynamic_service_charges JSONB DEFAULT '{}',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS invoice_items (
    id BIGSERIAL PRIMARY KEY,
    invoice_id VARCHAR(64) NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
    store_id VARCHAR(64) NOT NULL REFERENCES stores(id) ON DELETE CASCADE,
    product_id VARCHAR(64),
    product_name VARCHAR(255) NOT NULL,
    product_type VARCHAR(50) DEFAULT 'finished',
    product_price NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    product_quantity NUMERIC(12, 3) NOT NULL DEFAULT 1.000,
    discount_percentage NUMERIC(6, 2) DEFAULT 0.00,
    discounted_price NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    changed_price NUMERIC(14, 2) DEFAULT 0.00,
    product_total NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    tax_rate NUMERIC(6, 2),
    further_tax NUMERIC(6, 2),
    pct_code VARCHAR(50),
    unit_multiple INT DEFAULT 1,
    warehouse_id VARCHAR(64),
    warehouse_name VARCHAR(255),
    product_description TEXT,
    serial_enabled BOOLEAN DEFAULT FALSE,
    serial_no JSONB DEFAULT '[]',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS payments (
    id VARCHAR(64) PRIMARY KEY,
    store_id VARCHAR(64) NOT NULL REFERENCES stores(id) ON DELETE CASCADE,
    customer_id VARCHAR(64),
    customer_name VARCHAR(255),
    customer_type VARCHAR(50) DEFAULT 'customer',
    amount NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    payment_type VARCHAR(50) NOT NULL,
    payment_date TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    description TEXT,
    employee_id VARCHAR(64),
    employee_name VARCHAR(255),
    installment_id VARCHAR(64),
    created_by VARCHAR(64),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
